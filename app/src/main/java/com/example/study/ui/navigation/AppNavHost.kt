/** 底部导航的四个页签。 */
private data class BottomNavItem(
    val route: String,
    val label: String,
    val icon: ImageVector
)

private val bottomNavItems = listOf(
    BottomNavItem("study", "学习", Icons.Filled.School),
    BottomNavItem("records", "记录", Icons.Filled.BarChart),
    BottomNavItem("games", "游戏", Icons.Filled.VideogameAsset),
    BottomNavItem("settings", "词库", Icons.AutoMirrored.Filled.MenuBook)
)

@Composable
fun AppNavHost() {
    val navController = rememberNavController()
    val backStackEntry by navController.currentBackStackEntryAsState()
    val currentDestination = backStackEntry?.destination

    Scaffold(
        bottomBar = {
            NavigationBar {
                bottomNavItems.forEach { item ->
                    val selected = currentDestination?.hierarchy?.any { it.route == item.route } == true
                    NavigationBarItem(
                        selected = selected,
                        onClick = {
                            navController.navigate(item.route) {
                                popUpTo(navController.graph.findStartDestination().id) {
                                    saveState = true
                                }
                                launchSingleTop = true
                                restoreState = true
                            }
                        },
                        icon = { Icon(item.icon, contentDescription = item.label) },
                        label = { Text(item.label) }
                    )
                }
            }
        }
    ) { innerPadding ->
        NavHost(
            navController = navController,
            startDestination = "study",
            modifier = Modifier
                .fillMaxSize()
                .padding(innerPadding)
        ) {
            composable("study") { PlaceholderScreen("学习页") }
            composable("records") { PlaceholderScreen("记录页") }
            composable("games") { PlaceholderScreen("游戏页") }
            composable("settings") { PlaceholderScreen("词库页") }
        }
    }
}

/** 里程碑 1 的占位页面，后续里程碑会替换为真实页面。 */
@Composable
private fun PlaceholderScreen(title: String) {
    Box(modifier = Modifier.fillMaxSize(), contentAlignment = Alignment.Center) {
        Text(text = title)
    }
}
